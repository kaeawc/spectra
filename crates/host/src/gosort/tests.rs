#[test]
fn ties_land_where_go_puts_them() {
    for &(n, m, seed, want) in GO_ORDERS {
        let mut v = lcg(n, m, seed);
        slice(&mut v, |a, b| a.0 > b.0);
        let got: Vec<usize> = v.iter().map(|x| x.1).collect();
        assert_eq!(got, want, "n={n} m={m} seed={seed}");
    }
}

