/// The inputs the Go recording used: `n` items whose keys follow a C-style LCG modulo `m`.
fn lcg(n: usize, m: u32, seed: u32) -> Vec<(u32, usize)> {
    let mut s = seed;
    (0..n)
        .map(|i| {
            s = s.wrapping_mul(1_103_515_245).wrapping_add(12_345);
            ((s >> 16) % m, i)
        })
        .collect()
}

