#[test]
fn sorts_and_handles_small_inputs() {
    let mut empty: Vec<i32> = vec![];
    slice(&mut empty, |a, b| a < b);
    let mut one = vec![1];
    slice(&mut one, |a, b| a < b);
    let mut v: Vec<i64> = (0..1000).map(|i| (i * 7919) % 1009).collect();
    slice(&mut v, |a, b| a < b);
    assert!(v.windows(2).all(|w| w[0] <= w[1]));
    let mut d: Vec<i64> = (0..500).rev().collect();
    slice(&mut d, |a, b| a < b);
    assert_eq!(d, (0..500).collect::<Vec<_>>());
}
